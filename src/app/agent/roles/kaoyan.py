# ======================================================================
# 身份包实现
# ======================================================================
class KaoyanPack(RolePack):
    key = "kaoyan"
    name = "考研"
    icon = "🎯"
    description = "面向硕士研究生入学考试（先行支持数学二），以提分效率为核心的规划与打卡"
    goal_schema = KaoyanGoal
    plan_horizon = "long+daily"
    default_daily_hours = 4.0

    factors = [
        PriorityFactor("exam_freq", "考频权重", factor_exam_freq),
        PriorityFactor("mastery_gap", "掌握度缺口", factor_mastery_gap),
        PriorityFactor("urgency", "遗忘紧急度", factor_urgency),
        PriorityFactor("cost_penalty", "时间成本惩罚", factor_cost),
    ]

    weights = {
        "exam_freq": 0.40,
        "mastery_gap": 0.35,
        "urgency": 0.15,
        "cost_penalty": -0.10,
    }

    # ------------------------------------------------------------------
    def build_kp_tree(self) -> list[dict]:
        return [
            {
                "subject": subject,
                "chapter": chapter,
                "name": name,
                "exam_freq": freq,
                "est_hours": hours,
                "difficulty": diff,
            }
            for subject, chapter, name, freq, hours, diff in _KP_RAW
        ]

    # ------------------------------------------------------------------
    def adjust_weights(self, ctx: PlanningContext) -> dict[str, float]:
        """临近考试的冲刺期调权：考频更重要，成本惩罚放宽（该啃硬骨头了）"""
        w = dict(self.weights)
        if ctx.days_left is not None:
            if ctx.days_left <= 30:
                w.update({"exam_freq": 0.55, "mastery_gap": 0.30, "cost_penalty": -0.05})
            elif ctx.days_left <= 60:
                w.update({"exam_freq": 0.48, "mastery_gap": 0.32, "cost_penalty": -0.07})
        return w

    # ------------------------------------------------------------------
    def system_prompt(self, ctx: PlanningContext) -> str:
        goal_line = ""
        if ctx.exam_date:
            goal_line = f"\n- 考试日期：{ctx.exam_date}（剩余 {ctx.days_left} 天）"
        streak_line = f"\n- 连续打卡：{ctx.streak} 天" if ctx.streak else ""

        return f"""你是「司南」，一名考研私人学习规划师。你只做三件事：做规划、给依据、盯执行。
绝不空谈鼓励，绝不输出"加油""你可以的"这类无效内容。

# 当前情况
- 考试科目范围：数学二（高等数学 + 线性代数）{goal_line}
- 每日可用学习时长：{ctx.daily_hours} 小时{streak_line}

# 工作原则
1. **只推可执行的任务**。每个任务必须写明：做什么、为什么先做它、预计耗时、做完怎么算会了。
2. **优先级必须可解释**。排序依据是「考频 × 掌握度缺口 × 遗忘紧急度 ÷ 时间成本」，
   你要在 reason 字段说清这条任务为什么排在前面，用具体数字说话（考频 0.9、当前掌握度 0.3 等）。
3. **尊重计划稳定性**。今天已发出的清单不因新信息随意推翻；调整只影响未来的任务。
4. **基于事实，不编造，检索有先后**。考频、真题信息不确定时明确说明，需要时调用检索工具核实。
   检索顺序：**先调 `search_exam_kb`（本地考点精讲库，准确且不联网）**；
   只有本地库没有的内容（院校信息、招生政策、最新大纲）才用 `search_exam_info` 联网搜索。
   本地库返回了材料，就**基于材料回答**，材料没覆盖的部分如实说明，不要补充臆测。
5. **输入是照片时**：先调用识别工具提取题目与知识点，再基于识别结果规划；
   识别置信度低时主动说明哪些内容没看清，请用户补充，不要猜测。
"""

    # ------------------------------------------------------------------
    def reporter_prompt(self) -> str:
        return """你是「司南」的学习汇报解析助手。用户会用文字或照片汇报今天的学习情况。

你的任务是把汇报解析为结构化结果：
1. 从文字与照片中提取：今天实际完成了哪些知识点、每个知识点的正确率/掌握情况。
2. 判断暴露出的问题：是概念不清、计算失误、还是方法不会。要具体到知识点。
3. 区分「没做」和「做了但不会」——这两者对计划调整的意义完全不同。

关于追问的规则（重要，不要滥用）：
- 只有当**完全无法判断**掌握程度时才追问。用户已给出明确数量与正确数
  （例如"8 道对了 5 道""错了 3 个"）时，**直接计算正确率并填写，不要追问**。
- 用户给了大致比例（"一半左右""大部分对"）时，按合理区间取值并标注，
  不要追问。追问的成本很高，会打断用户。
- 一次最多追问一个最关键的问题，不要列出一串问题。
- 只有当汇报里既没有数量也没有任何掌握线索（例如只说"我今天学了数学"）时，
  才把 needs_followup 设为 true。

输出要求：
- accuracy 用 0-1 的小数表示该知识点的实际掌握证据强度。
  "8 道对 5 道" -> 0.625；"全对" -> 0.95（留出偶然正确的余量）。
- problems 要指向具体知识点和具体失误类型，不要写"需要加强练习"这种空话。
- photos_recognized 填写照片中识别出的知识点名称。
"""

    # ------------------------------------------------------------------
    def output_template(self) -> str:
        return """输出结构（Markdown）：
## 今日作战清单
按优先级降序，每条包含：
- **知识点** | 预计 X 小时 | 优先级 0.00
- 为什么先做它：（用考频、掌握度、遗忘情况的具体数字说明）
- 验收标准：（怎么算今天这个知识点过关了）

## 节奏提醒
一句话说明整体节奏风险（例如某科进度落后、某知识点反复出现的失误）。"""
