class ZhuanshengbenPack(RolePack):
    key = "zhuanshengben"
    name = "专升本"
    icon = "📘"
    description = "面向专科升本科考试（英语 / 计算机 / 政治 / 高等数学四大科目）"
    goal_schema = ZhuanshengbenGoal
    plan_horizon = "long+daily"
    default_daily_hours = 3.0

    # 与考研的差别一：多一个「难度惩罚」因子。
    # 专升本考生基础跨度极大，一上来就推最难的点会直接劝退；
    # 负权重意味着"越难越往后排"，先让他做出成就感，再啃硬骨头。
    factors = [
        PriorityFactor("exam_freq", "真题频率", factor_exam_freq),
        PriorityFactor("mastery_gap", "掌握度缺口", factor_mastery_gap),
        PriorityFactor("urgency", "遗忘紧急度", factor_urgency),
        PriorityFactor("difficulty_penalty", "难度惩罚", factor_difficulty),
        PriorityFactor("cost_penalty", "时间成本惩罚", factor_cost),
    ]

    # 与考研的差别二：掌握度缺口权重更高。
    # 考研的主要矛盾是"技巧是否熟练"，专升本的主要矛盾是"基础扎不扎实"，
    # 所以缺口（=1-掌握度）在排序里的话语权更大。
    weights = {
        "exam_freq": 0.38,
        "mastery_gap": 0.38,          # 考研是 0.35
        "urgency": 0.14,
        "difficulty_penalty": -0.06,  # 考研没有这个因子
        "cost_penalty": -0.08,
    }

    # ------------------------------------------------------------------
    def adjust_weights(self, ctx: PlanningContext) -> dict[str, float]:
        """按剩余天数动态调权 —— 用的是基类留的可选钩子。

        ★ 这是 base.py 里 `adjust_weights` 的第一个真实使用者。
          为什么要有这个钩子：**同一套因子，在不同阶段该有不同的话语权。**

            还剩 180 天以上  → 长线，先把基础铺开（缺口权重要大）
            还剩 60~180 天   → 常规推进，按默认权重
            只剩 60 天以内   → 冲刺，只抓高频（考频权重上调，难度惩罚加重）

          没有这个钩子的话，就只能写三套权重常量 + 在引擎里 if-else 判断阶段，
          而"判断阶段"恰好属于身份知识 —— 它就该待在这里。
        """
        w = dict(self.weights)
        days = ctx.days_left

        if days is not None and days <= 60:
            # 冲刺期：考频说话，难题该放弃就放弃
            w["exam_freq"] = 0.46
            w["mastery_gap"] = 0.30
            w["difficulty_penalty"] = -0.12
        elif days is not None and days >= 180:
            # 长线期：补基础优先，难易暂时不惩罚（迟早都要学）
            w["mastery_gap"] = 0.44
            w["exam_freq"] = 0.34
            w["difficulty_penalty"] = -0.02

        return w

    # ------------------------------------------------------------------
    def build_kp_tree(self) -> list[dict]:
        return [
            {
                "subject": s, "chapter": c, "name": n,
                "exam_freq": f, "est_hours": h, "difficulty": d,
            }
            for s, c, n, f, h, d in _KP_RAW
        ]

    # ------------------------------------------------------------------
    def reporter_prompt(self) -> str:
        return """你是「司南」的专升本学习汇报解析助手。
从用户的文字或照片中提取：完成的知识点、正确率、暴露的问题。

专升本考生的基础跨度极大（从初中水平到专科毕业都有），因此判断"错误原因"
比统计"错了几道"更重要：

    · 若是「完全看不懂 / 没思路 / 公式不认识」→ 判为 **基础缺口**，
      这类问题要回到前置知识点补课，继续刷题只会浪费时间。
    · 若是「会做但算错 / 看错题 / 单位漏了」→ 判为 **熟练度问题**，
      靠限时练习解决。
    · 若是「方法选错 / 用了复杂解法」→ 判为 **方法问题**，
      需要补充解题技巧。

请在 problems 字段里用上面这三类措辞，规划器会据此决定是"补前置"还是"加练习"。
信息不足时主动追问，绝对不要猜测用户的错误原因。"""

    # ------------------------------------------------------------------
    def system_prompt(self, ctx: PlanningContext) -> str:
        return f"""你是「司南」，一名专升本私人学习规划师。

【当前情况】
- 考试日期：{ctx.exam_date or '（未设置）'}（剩余 {ctx.days_left if ctx.days_left is not None else '?'} 天）
- 每日可用时长：{ctx.daily_hours} 小时
- 当前连续打卡：{ctx.streak} 天

【工作原则】
1. **基础缺口优先于刷题量**。前置知识不牢时先补前置，不要为了"今天做了 20 题"
   这种好看的数字堆量。宁可今天只推进一个考点，也不要在不会的地方空转。
2. 每个任务写明：做什么、为什么先做它、预计耗时、做完怎么算会了。
3. 优先级依据「真题频率 × 掌握度缺口 × 遗忘紧急度 ÷ 时间成本」，
   理由要用具体数字说话（考频 0.90、当前掌握度 0.30 之类）。
4. 尊重计划稳定性：今天已发出的清单不因新信息随意推翻，调整只影响未来。
5. 检索顺序：**先调 `search_exam_kb`（本地考点精讲）**，
   本地没有的（院校信息、招生政策、最新大纲）再用 `search_exam_info` 联网。
6. 不空谈鼓励，不给无法执行的任务。用户要的是"今天做什么"，不是"加油"。
"""
